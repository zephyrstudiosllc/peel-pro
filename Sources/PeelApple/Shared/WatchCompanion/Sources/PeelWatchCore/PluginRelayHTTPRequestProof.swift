#if !os(watchOS)
import Foundation
import CryptoKit

/// Immutable binding to the exact bytes about to be sent. Credential signers
/// receive this after encoding; no token is placed in the body or proof object.
public struct PluginRelayHTTPRequestProof: Equatable, Sendable {
    public let method: String
    public let path: String
    public let bodySHA256: String
    public init(method: String, path: String, body: Data) throws {
        let paths: Set<String> = ["/v1/watch/connect", "/v1/watch/status", "/v1/watch/send",
            "/v1/watch/replies", "/v1/watch/disconnect", "/v1/native/route-grant",
            "/v1/native/plugin/review", "/v1/native/plugin/approve", "/v1/native/renew",
            "/v1/native/pro/challenge", "/v1/native/pro/evidence", "/v1/native/pro/withdraw"]
        guard method == "POST", paths.contains(path), !body.isEmpty, body.count <= 256 * 1_024 else {
            throw PluginRelayHTTPError.invalidConfiguration
        }
        self.method = method; self.path = path
        bodySHA256 = SHA256.hash(data: body).map { String(format: "%02x", $0) }.joined()
    }

    /// LOCKED request-proof v1 with the relay backend. Timestamp and nonce are
    /// freshly generated by the enrolled phone signer; nonce is exactly32 bytes
    /// in canonical unpadded base64url. No final LF. The backend accepts±30s and
    /// consumes a proof nonce once; this helper does not establish those grants.
    public func canonicalBytes(enrollmentID: String, unixSeconds: Int64, nonce: String) throws -> Data {
        guard PluginRelayValidation.opaque(enrollmentID), unixSeconds >= 0,
              nonce.utf8.count == 43, nonce.utf8.allSatisfy({ (48...57).contains($0) || (65...90).contains($0)
                || (97...122).contains($0) || $0 == 45 || $0 == 95 }),
              let decoded = Data(base64Encoded: nonce.replacingOccurrences(of: "-", with: "+").replacingOccurrences(of: "_", with: "/") + "="),
              decoded.count == 32, Self.base64URL(decoded) == nonce else { throw PluginRelayHTTPError.invalidConfiguration }
        return Data(["peel-native-request-v1", method, path, bodySHA256, String(unixSeconds), nonce, enrollmentID]
            .joined(separator: "\n").utf8)
    }
    private static func base64URL(_ data: Data) -> String {
        data.base64EncodedString().replacingOccurrences(of: "+", with: "-")
            .replacingOccurrences(of: "/", with: "_").replacingOccurrences(of: "=", with: "")
    }
}

/// Additive proof-aware authorizer. Production enrolled phone sessions MUST
/// implement this method; legacy test adapters retain their existing API. The
/// signature covers this exact request; headers remain private/redacted in the
/// returned authorization attachment and current-lease checks still apply.
public protocol PluginRelayHTTPRequestAuthorizer: PluginRelayHTTPAuthorizer {
    func authorization(for context: PluginRelayHTTPContext, scope: PluginRelayHTTPScope,
                       trustedOrigin: URL, request: PluginRelayHTTPRequestProof) throws -> PluginRelayHTTPAuthorization
}
#endif
